#!/usr/bin/env python3
"""Emit PyBullet URDFs whose extents equal cuTAMP's own object models.

The baseline's stock blocks are 0.2 m tall while the vessels cuTAMP plans for
are 0.135 m and 0.12 m, and their footprints differ too, so a planner
comparison on the stock blocks compares object geometry as much as planners.
cuTAMP represents every object as a cuboid (TAMP/tamp/src/envs/utils.py
ENTITIES), so the same cuboids can be written as URDFs and both planners given
identical geometry.
"""
import os

# name -> (x, y, z) extents [m], mirroring ENTITIES in envs/utils.py
DIMS = {
    "beaker":      (0.05, 0.05, 0.135),
    "flask":       (0.07, 0.07, 0.12),
    "magnet":      (0.010, 0.010, 0.035),
    "box":         (0.108, 0.108, 0.08),
    "stirrer":     (0.18, 0.18, 0.09),
    "table":       (1.5, 1.5, 0.02),
    "goal_region": (0.1, 0.1, 0.01),
    # The Move task's goal tray. envs/move.py copies the TRAY's footprint into
    # box_region, so 0.15 m -- not the 0.2 m box_region authored in ENTITIES,
    # which was wide enough for the box to satisfy the goal hanging off the edge.
    "box_goal":    (0.15, 0.15, 0.01),
}
MASS = {"beaker": 0.2, "flask": 0.3, "magnet": 0.02, "box": 0.5}

TEMPLATE = """<?xml version="1.0"?>
<!-- Generated by make_models.py; extents match cuTAMP's ENTITIES cuboid. -->
<robot name="{name}">
  <link name="base_link">
    <inertial>
      <origin xyz="0 0 0"/>
      <mass value="{mass}"/>
      <inertia ixx="{ixx}" ixy="0" ixz="0" iyy="{iyy}" iyz="0" izz="{izz}"/>
    </inertial>
    <visual>
      <origin xyz="0 0 0"/>
      <geometry><box size="{sx} {sy} {sz}"/></geometry>
      <material name="grey"><color rgba="0.7 0.7 0.7 1"/></material>
    </visual>
    <collision>
      <origin xyz="0 0 0"/>
      <geometry><box size="{sx} {sy} {sz}"/></geometry>
    </collision>
  </link>
</robot>
"""


def main():
    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "models")
    os.makedirs(here, exist_ok=True)
    for name, (sx, sy, sz) in DIMS.items():
        m = MASS.get(name, 1.0)
        ixx = m * (sy * sy + sz * sz) / 12.0
        iyy = m * (sx * sx + sz * sz) / 12.0
        izz = m * (sx * sx + sy * sy) / 12.0
        path = os.path.join(here, "%s.urdf" % name)
        with open(path, "w") as fh:
            fh.write(TEMPLATE.format(name=name, mass=m, sx=sx, sy=sy, sz=sz,
                                     ixx=ixx, iyy=iyy, izz=izz))
        print("wrote %s  %.3f x %.3f x %.3f" % (path, sx, sy, sz))


if __name__ == "__main__":
    main()

