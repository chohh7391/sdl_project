"""Write the cell's robot registry: the core's, plus config/robot_config_additions.yaml.

Usage: make_robot_config.py <additions.yaml> <output dir>

Every registry file of the installed cho_robot_config is copied as text, so its
comments survive; a robot named in the additions gets one line,
``additional_arm: [...]``, right under its top-level ``controllers:``. A core
entry that already declares ``additional_arm`` is refused rather than merged:
the core's list and the cell's have to be read together by a person once.

The result is loaded back through cho_robot_config, every profile of every
robot, so a registry the core would refuse never gets installed.
"""

import os
from pathlib import Path
import re
import sys

from ament_index_python.packages import get_package_share_directory
import yaml

HEADER = (
    '# GENERATED by sdl_cell_bringup scripts/make_robot_config.py from\n'
    '# {source}. Do not edit: change\n'
    '# sdl_cell_bringup/config/robot_config_additions.yaml and rebuild.\n'
)


def core_registry_dir():
    """The installed core registry, whatever CHO_ROBOT_CONFIG_DIR says now.

    A terminal that sourced this workspace already points CHO_ROBOT_CONFIG_DIR
    at a previous build's output; reading that would add the names twice.
    """
    return Path(get_package_share_directory('cho_robot_config')) / 'config'


def load_additions(path):
    with open(path, encoding='utf-8') as stream:
        additions = yaml.safe_load(stream) or {}
    if not isinstance(additions, dict):
        raise ValueError('%s: expected {robot_type: {additional_arm: [...]}}' % path)
    for robot_type, entry in additions.items():
        if not isinstance(entry, dict) or set(entry) != {'additional_arm'}:
            raise ValueError('%s: %s must hold exactly additional_arm' % (path, robot_type))
        names = entry['additional_arm']
        if not isinstance(names, list) or not names or not all(
                isinstance(name, str) and name for name in names):
            raise ValueError('%s: %s.additional_arm must be a non-empty list of names'
                             % (path, robot_type))
    return additions


def with_additional_arm(text, names, label):
    """*text* with ``additional_arm: [names]`` as the first key under ``controllers:``."""
    document = yaml.safe_load(text) or {}
    if 'additional_arm' in (document.get('controllers') or {}):
        raise ValueError(
            '%s: the core entry declares controllers.additional_arm itself; merge it with '
            'robot_config_additions.yaml by hand' % label)
    lines = text.splitlines(keepends=True)
    for index, line in enumerate(lines):
        if re.match(r'^controllers:\s*(#.*)?$', line):
            lines.insert(index + 1, '  additional_arm: [%s]\n' % ', '.join(names))
            return ''.join(lines)
    raise ValueError('%s: no top-level controllers: section' % label)


def check(output_dir, additions):
    """Load every robot and profile from *output_dir* through the core's loader."""
    os.environ['CHO_ROBOT_CONFIG_DIR'] = str(output_dir)
    from cho_robot_config import available_profiles, available_robot_types, load_robot_config
    for robot_type in available_robot_types():
        for profile in available_profiles(robot_type):
            load_robot_config(robot_type, profile)
    for robot_type, entry in additions.items():
        declared = load_robot_config(robot_type)['controllers'].get('additional_arm') or []
        missing = [name for name in entry['additional_arm'] if name not in declared]
        if missing:
            raise ValueError('%s: %s did not reach controllers.additional_arm'
                             % (robot_type, missing))


def main(argv):
    if len(argv) != 3:
        sys.stderr.write(__doc__)
        return 2
    additions = load_additions(argv[1])
    output_dir = Path(argv[2])
    source = core_registry_dir()
    paths = sorted(source.glob('*.yaml'))
    unknown = sorted(set(additions) - {path.stem for path in paths})
    if unknown:
        raise ValueError('robot_config_additions.yaml names robots the core has not: %s' % unknown)
    output_dir.mkdir(parents=True, exist_ok=True)
    for stale in output_dir.glob('*.yaml'):
        stale.unlink()
    for path in paths:
        text = path.read_text(encoding='utf-8')
        if path.stem in additions:
            text = with_additional_arm(
                text, additions[path.stem]['additional_arm'], path.name)
        (output_dir / path.name).write_text(
            HEADER.format(source=path.resolve()) + text, encoding='utf-8')
    check(output_dir, additions)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
